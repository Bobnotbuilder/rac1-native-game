run() {
  local name=$1 frames=$2 at=$3 seq=$4 shots=$5 extra=$6
  local d=$OUT/$name
  mkdir -p "$d"
  (cd "$d" && ln -sfn "$W/assets" assets && env RAC1_HEADLESS=1 RAC1_LEVEL=5 RAC1_FRAMES="$frames" RAC1_GIVE_FRAME=780 RAC1_GIVE_ITEMS="$ITEMS" \
     RAC1_HERO_AT="$at" RAC1_SIM_INPUT="seq:$seq" RAC1_SEQ_TRACE=10 RAC1_SHOTS="$shots" $extra timeout 900 "$W/${RAC1_BUILD:-build}/rac1-native" > run.log 2>&1)
  local rc=$?
  local states
  states=$(grep '^\[seq\]' "$d/run.log" | awk '$3 >= 790 {print $5}' | uniq | tr '\n' ' ' | cut -c1-120)
  local todo
  todo=$(grep TODO_PORT "$d/run.log" | grep -Ev "$HOST" | sort -u | sed 's/^\[TODO_PORT\] Unported call to //' | tr '\n' ';')
  echo "$name rc=$rc states: $states"
  [ -n "$todo" ] && echo "  TODO_PORT: $todo"
  grep '^\[seq\]' "$d/run.log" | tail -1 | sed 's/^/  last: /'
}

if [ "$1" = dumps ]; then  # oracle batch 140's inputs: the RAM in the race (frame 1200: the racers, the board, the race HUD) and on its result
  # screen (game mode 4, kind 0: frame 22990 of the "race" scenario's line)
  mkdir -p "$DUMPS/rilgar_0387"
  for fr in 1200 22990; do
    d=$OUT/dumps$fr
    mkdir -p "$d"
    (cd "$d" && ln -sfn "$W/assets" assets && env RAC1_HEADLESS=1 RAC1_LEVEL=5 RAC1_FRAMES=$((fr + 5)) RAC1_GIVE_FRAME=780 RAC1_GIVE_ITEMS="$ITEMS" \
       RAC1_HERO_AT="439@800,2,0,0.5,-1.57" RAC1_SIM_INPUT="seq:0:l3" RAC1_AUTOPILOT="820-23000:wp:$RACE_WP" RAC1_RAMHASH=/dev/null \
       RAC1_RAMDUMP="$fr,$DUMPS/rilgar_0387/race$fr.bin" timeout 1800 "$W/${RAC1_BUILD:-build}/rac1-native" > run.log 2>&1)
    ls -l "$DUMPS/rilgar_0387/race$fr.bin"
  done
  exit
fi

want=("$@")
for s in "${SCEN[@]}"; do
  IFS='|' read -r name frames at seq shots extra <<< "$s"
  if [ ${#want[@]} -gt 0 ]; then
    hit=0; for x in "${want[@]}"; do [ "$x" = "$name" ] && hit=1; done
    [ $hit = 0 ] && continue
  fi
  run "$name" "$frames" "$at" "$seq" "$shots" "$extra"
done
